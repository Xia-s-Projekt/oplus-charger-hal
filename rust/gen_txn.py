# gen_txn.py - emits rust/src/txn.rs from aidl/vendor/oplus/hardware/charger/ICharger.aidl
# and the generated C++ ICharger.cpp onTransact switch.
#
# The transaction code is `index + 1`: ICharger.cpp emits
# `case (FIRST_CALL_TRANSACTION + N)` and FIRST_CALL_TRANSACTION is 1.
#
# Each entry is parsed from the AIDL declaration line, e.g.
#   int getAcType();
#   int setPsyOtgSwitch(String value0);
#   testKitFeatureTestResult testKitFeatureTest(int arg0, String value1, int arg2);
#
# Type mapping:
#   int                      -> i32
#   boolean                  -> bool
#   String                   -> &str
#   testKitFeatureTestResult -> &mut TestKitResult
#
# Usage: python3 rust/gen_txn.py
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AIDL = ROOT / "aidl/vendor/oplus/hardware/charger/ICharger.aidl"
OUT = ROOT / "rust/src/txn.rs"
CPP = ROOT / "standalone/build/aidl_gen/vendor/oplus/hardware/charger/ICharger.cpp"
MOD = ROOT / "rust/src/charger/mod.rs"
BRIDGE = ROOT / "rust/src/charger/bridge.rs"

TYPE_MAP = {
    "int": "i32",
    "boolean": "bool",
    "String": "&str",
    "testKitFeatureTestResult": "&mut TestKitResult",
}

RET_TYPES = {
    "int": "i32",
    "boolean": "bool",
    "String": "String",
    "testKitFeatureTestResult": "TestKitResult",
}

PREAMBLE = """// GENERATED by rust/gen_txn.py from ICharger.aidl + the generated ICharger.cpp
// onTransact switch.  Do not edit by hand.
//
// The wire contract, in the shipped order:
//   * the request parcel holds the arguments in declaration order;
//   * the reply holds the status header, then - only when the status is OK -
//     the single return value;
//   * testKitFeatureTest returns a structured parcelable, which is written
//     with the AIDL parcelable header (a 4-byte size that is backpatched
//     after the fields), not as a bare field sequence.
//
// getInterfaceVersion / getInterfaceHash are the AIDL stable-interface
// negotiation transactions.  The generated server answers them with
// ICharger::version and ICharger::hash from the generated header
// (--version=6 --hash=ede5e600328119dbf1c38269f810a3fdce74029f), so this
// dispatcher answers with the same two constants.

// The stock oos15_old V6 HAL answers 6 / ede5e600..., and our VINTF manifest
// declares <version>6</version>, so the port matches it.  Evidence: the
// stock lib64/vendor.oplus.hardware.charger-V6-ndk_platform.so has
// `mov w9, #0x6` in BnCharger::getInterfaceVersion (.text 0x20bd0), and
// ede5e600... is the only 40-hex string in that library.

use crate::binder::{Parcel, STATUS_OK, STATUS_UNKNOWN_TRANSACTION};
use crate::charger::Charger;

pub struct TestKitResult {
    pub ret: i32,
    pub str: String,
}

// ICharger.h:35-36, from the aidl invocation that generated the stubs.
pub const INTERFACE_VERSION: i32 = 6;
pub const INTERFACE_HASH: &str = "ede5e600328119dbf1c38269f810a3fdce74029f";

// android.os.IBinder.FIRST_CALL_TRANSACTION + 16777214 / + 16777213.
const TXN_GET_INTERFACE_VERSION: u32 = 0xFFFFFF;
const TXN_GET_INTERFACE_HASH: u32 = 0xFFFFFE;

"""


def parse_aidl():
    """Return [(name, ret, [(aidl_type, arg_name), ...])] in declaration order."""
    text = AIDL.read_text()
    body = text.split("interface ICharger {", 1)[1]
    body = body.rsplit("}", 1)[0]
    body = re.sub(r"/\*.*?\*/", " ", body, flags=re.S)
    body = re.sub(r"//[^\n]*", " ", body)
    body = " ".join(body.split())

    decls = []
    for m in re.finditer(r"([\w<>, ]+?)\s+(\w+)\s*\(([^)]*)\)\s*;", body):
        ret = m.group(1).strip()
        name = m.group(2)
        args_raw = m.group(3).strip()
        args = []
        if args_raw:
            for a in args_raw.split(","):
                a = a.strip()
                if not a:
                    continue
                parts = a.rsplit(None, 1)
                if len(parts) != 2:
                    raise SystemExit(f"cannot parse argument: {a!r} in {name}")
                args.append((parts[0].strip(), parts[1]))
        decls.append((name, ret, args))

    # Cross-check the count and the order against the generated C++ switch.
    # The onTransact switch also carries getInterfaceVersion /
    # getInterfaceHash at FIRST_CALL_TRANSACTION + 16777214 / + 16777213;
    # those are handled separately, not by the method table.
    cpp = CPP.read_text()
    ontransact = cpp.split("_onTransact", 1)[1].rsplit("defineClass", 1)[0]
    order = re.findall(r"FIRST_CALL_TRANSACTION \+ (\d+)[^\n]*/\*(\w+)\*/", ontransact)
    # The two stable-interface transactions sit at +16777213 / +16777214 and
    # are not part of the method table.
    order = [(i, n) for i, n in order if int(i) < 1000]
    if len(order) != len(decls):
        raise SystemExit(
            f"count mismatch: aidl has {len(decls)} methods, "
            f"generated ICharger.cpp has {len(order)}"
        )
    for idx, (name, _ret, _args) in enumerate(decls):
        if order[idx][1] != name:
            raise SystemExit(
                f"order mismatch at {idx}: aidl {name!r} vs cpp {order[idx][1]!r}"
            )
    return decls


def main():
    decls = parse_aidl()

    lines = [PREAMBLE]
    lines.append(f"pub const METHOD_COUNT: usize = {len(decls)};\n")
    # The methods are inherent on Charger: the hand-written ones live in
    # charger/mod.rs, the generated forwards in charger/bridge.rs.
    for name, ret, args in decls:
        pass

    lines.append("/// Dispatch one transaction.  Mirrors the generated C++")
    lines.append("/// _aidl_..._onTransact switch statement for statement.")
    lines.append(
        "pub fn dispatch(c: &Charger, code: u32, in_p: &Parcel, out_p: &mut Parcel) -> i32 {"
    )
    # The version/hash transactions are answered before the method table, the
    # way the generated onTransact does.
    lines.append("    if let Some(status) = dispatch_interface_query(code, out_p) {")
    lines.append("        return status;")
    lines.append("    }")
    lines.append("    match code {")

    for idx, (name, ret, args) in enumerate(decls):
        lines.append(f"        {idx + 1} => {{")
        for i, (t, _) in enumerate(args):
            if t in ("int", "boolean"):
                reader = "read_i32" if t == "int" else "read_bool"
                lines.append(f"            let a{i} = match in_p.{reader}() {{")
                lines.append(f"                Ok(v) => v,")
                lines.append(f"                Err(_) => return STATUS_UNKNOWN_TRANSACTION,")
                lines.append(f"            }};")
            elif t == "String":
                lines.append(f"            let a{i} = match in_p.read_string() {{")
                lines.append(f"                Ok(v) => v,")
                lines.append(f"                Err(_) => return STATUS_UNKNOWN_TRANSACTION,")
                lines.append(f"            }};")
            else:
                raise SystemExit(f"unhandled arg type {t}")
        # The trait signatures borrow string parameters; the parcel read
        # produces an owned String.
        call_args = ", ".join(f"&a{i}" if t == "String" else f"a{i}"
                              for i, (t, _) in enumerate(args))
        if ret == "testKitFeatureTestResult":
            lines.append(f"            let mut parcelable = c.txn_{name}({call_args});")
            lines.append(f"            if !out_p.write_status_ok() {{")
            lines.append(f"                return STATUS_UNKNOWN_TRANSACTION;")
            lines.append(f"            }}")
            lines.append(f"            write_parcelable(out_p, &parcelable);")
        else:
            lines.append(f"            let v = c.txn_{name}({call_args});")
            lines.append(f"            if !out_p.write_status_ok() {{")
            lines.append(f"                return STATUS_UNKNOWN_TRANSACTION;")
            lines.append(f"            }}")
            if ret == "int":
                lines.append(f"            out_p.write_i32(v);")
            elif ret == "boolean":
                lines.append(f"            out_p.write_bool(v);")
            elif ret == "String":
                lines.append(f"            out_p.write_string(&v);")
        lines.append("            STATUS_OK")
        lines.append("        }")

    lines.append("        _ => STATUS_UNKNOWN_TRANSACTION,")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("// The two stable-interface negotiation transactions the generated")
    lines.append("// server answers.  They are not in the method table above.")
    lines.append("pub fn dispatch_interface_query(code: u32, out_p: &mut Parcel) -> Option<i32> {")
    lines.append("    match code {")
    lines.append("        TXN_GET_INTERFACE_VERSION => {")
    lines.append("            if !out_p.write_status_ok() {")
    lines.append("                return Some(STATUS_UNKNOWN_TRANSACTION);")
    lines.append("            }")
    lines.append("            out_p.write_i32(INTERFACE_VERSION);")
    lines.append("            Some(STATUS_OK)")
    lines.append("        }")
    lines.append("        TXN_GET_INTERFACE_HASH => {")
    lines.append("            if !out_p.write_status_ok() {")
    lines.append("                return Some(STATUS_UNKNOWN_TRANSACTION);")
    lines.append("            }")
    lines.append("            out_p.write_string(INTERFACE_HASH);")
    lines.append("            Some(STATUS_OK)")
    lines.append("        }")
    lines.append("        _ => None,")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("/// The structured-parcelable write: a 4-byte size placeholder, the")
    lines.append("/// fields, then the size backpatched.  Identical to the generated")
    lines.append("/// testKitFeatureTestResult::writeToParcel.")
    lines.append("fn write_parcelable(out_p: &mut Parcel, r: &TestKitResult) {")
    lines.append("    let start = out_p.data_position();")
    lines.append("    out_p.write_i32(0);")
    lines.append("    out_p.write_i32(r.ret);")
    lines.append("    out_p.write_string(&r.str);")
    lines.append("    let end = out_p.data_position();")
    lines.append("    out_p.set_data_position(start);")
    lines.append("    out_p.write_i32(end - start);")
    lines.append("    out_p.set_data_position(end);")
    lines.append("}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"generated {OUT}: {len(decls)} methods")

    emit_bridge(decls)


def emit_bridge(decls):
    """Emit the delegating ChargerTxn impl for the generated accessors.

    The hand-written methods live in charger/mod.rs and implement ChargerTxn
    themselves; everything else is a thin forward to the accessor of the same
    name produced by gen_accessors.py.  Both impl blocks are for the same
    trait, which Rust allows.
    """
    mod_src = MOD.read_text()
    hand = set(re.findall(r"fn txn_(\w+)\(", mod_src))

    out = [
        "// GENERATED by rust/gen_txn.py.  Do not edit by hand.",
        "//",
        "// ChargerTxn forwarding stubs for the accessors emitted by",
        "// gen_accessors.py.  The hand-written methods implement the trait",
        "// themselves in charger/mod.rs.",
        "",
        "use crate::charger::Charger;",
        "",
        "impl Charger {",
    ]
    n = 0
    for name, ret, args in decls:
        if name in hand:
            continue
        params = ", ".join(f"a{i}: {TYPE_MAP[t]}" for i, (t, _) in enumerate(args))
        sig = "&self" if not params else f"&self, {params}"
        call = ", ".join(f"a{i}" for i, (t, _) in enumerate(args))
        out.append(f"    pub(crate) fn txn_{name}({sig}) -> {RET_TYPES[ret]} {{")
        out.append(f"        self.{name}({call})")
        out.append("    }")
        n += 1
    out.append("}")
    BRIDGE.write_text("\n".join(out) + "\n")
    print(f"generated {BRIDGE}: {n} forwarding stubs "
          f"({len(hand)} hand-written in charger/mod.rs)")


if __name__ == "__main__":
    main()
